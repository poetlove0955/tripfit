/* GET /api/me — "지금 누가 들어와 있나, 그리고 어느 문이 열려 있나".
 *
 * ⭐ 화면은 이 한 곳만 물어보면 된다. 문이 늘어나도(네이버·애플…) 화면은 안 고친다.
 *    켜진 문만 `문` 목록에 담아 주고, 화면은 **받은 것만 그린다** —
 *    그래서 키를 안 넣은 문은 단추 자체가 안 생긴다.
 *    (반쯤 켜져서 손님 앞에서 오류를 내는 것보다 아예 없는 게 낫다)
 */
import { 지금누구, 카카오켜졌나, 네이버켜졌나, 답 } from '../_lib/세션.js';

export async function onRequestGet({ request, env }) {
  const 나 = await 지금누구(request, env);
  const 문 = [];
  if (카카오켜졌나(env)) 문.push({ 길: 'kakao', 이름: '카카오' });
  if (네이버켜졌나(env)) 문.push({ 길: 'naver', 이름: '네이버' });

  /* ⭐ 대표를 알아보는 방법이 비밀번호가 아니라 **카카오 회원번호**다.
   *    외울 게 하나도 안 늘고, 대표는 그냥 늘 하던 대로 로그인만 하면 된다. */
  const 적은것 = String(env.ADMIN_KAKAO_ID || '').trim();
  const 대표 = !!(적은것 && 나 && String(나.번호) === 적은것);

  return 답({
    들어옴: !!나,
    닉: 나 ? 나.닉 : '',
    길: 나 ? 나.길 : '',
    대표,
    문,
  });
}
